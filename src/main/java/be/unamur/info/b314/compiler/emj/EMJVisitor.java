    @Override
    public Object visitFunctionCall(EMJParser.FunctionCallContext ctx) {
        String funcName = ctx.EMOJI_ID().getText();

        // Verifier que la fonction existe
        Symbol funcSymbol = symbolTable.lookupFunction(funcName);
        if (funcSymbol == null) {
            errorLogger.addError(new EMJError("Function '" + funcName + "' is not declared", ctx.getText(), ctx.getStart().getLine()));
            return null;
        }

        // Verifier le nombre de parametres
        int expectedParams = funcSymbol.getParamCount();
        int actualParams = ctx.rightExpression() != null ? ctx.rightExpression().size() : 0;

        if (expectedParams != actualParams) {
            errorLogger.addError(new EMJError("Function '" + funcName + "' expects " + expectedParams + " parameters but got " + actualParams, ctx.getText(), ctx.getStart().getLine()));
            return funcSymbol.getType();
        }

        // Verifier les types des parametres
        Symbol.Type[] expectedTypes = funcSymbol.getParamTypes();
        for (int i = 0; i < actualParams; i++) {
            Symbol.Type actualType = (Symbol.Type) visit(ctx.rightExpression(i));
            if (actualType != null && expectedTypes[i] != null && actualType != expectedTypes[i]) {
                errorLogger.addError(new EMJError("Function '" + funcName + "' parameter " + (i + 1) + " expects " + expectedTypes[i] + " but got " + actualType, ctx.rightExpression(i).getText(), ctx.rightExpression(i).getStart().getLine()));
            }
        }

        return funcSymbol.getType();
    }


