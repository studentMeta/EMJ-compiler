    // =========================================================================
    // FONCTION && MAIN
    // =========================================================================
    @Override
    public Object visitMainFunction(EMJParser.MainFunctionContext ctx) {
        symbolTable.enterScope("main");

        // Visite de toutes les instructions du corps de la fonction main
        for (EMJParser.InstructionContext instrCtx : ctx.instruction()) {
            visit(instrCtx);
        }

        symbolTable.exitScope();
        return null;
    }

    @Override
    public Object visitFunctionDeclaration(EMJParser.FunctionDeclarationContext ctx) {
        if (preliminaryPass) return null;

        String funcName;
        Symbol.Type returnType;

        if (ctx.typeDeclaration() == null) {
            funcName = ctx.EMOJI_ID().getText();
            returnType = Symbol.Type.VOID;
        } else {
            funcName = ctx.EMOJI_ID().getText();
            returnType = resolveType(ctx.typeDeclaration());
        }

        // Entrer dans la portee de la fonction
        symbolTable.enterScope(funcName);

        // Enregistrer les parametres comme symboles dans la portee
        EMJParser.FunctionParametersContext paramsCtx = ctx.functionParameters();
        if (paramsCtx != null && paramsCtx.typeDeclaration() != null) {
            for (int i = 0; i < paramsCtx.typeDeclaration().size(); i++) {
                String paramName = paramsCtx.EMOJI_ID(i).getText();
                Symbol.Type paramType = resolveType(paramsCtx.typeDeclaration(i));

                // Verification des noms de parametres en double
                if (symbolTable.lookupParameterLocal(paramName) != null) {
                    errorLogger.addError(new EMJError("Duplicate parameter '" + paramName + "' in function '" + funcName + "'", ctx.getText(), ctx.getStart().getLine()));
                } else {
                    symbolTable.addSymbol(new Symbol(paramName, Symbol.Kind.PARAMETER, paramType, funcName));
                }
            }
        }

        // Visiter toutes les instructions du corps de la fonction
        for (EMJParser.InstructionContext instrCtx : ctx.instruction()) {
            visit(instrCtx);
        }

        // Verification du type de retour
        if (returnType == Symbol.Type.VOID) {
            // Fonction void : le retour doit etre 🌀 (deja forcer dans le parser)
        } else {
            // Fonction typee : verifier le type de l'expression de retour
            EMJParser.RightExpressionContext returnExpr = ctx.rightExpression();
            if (returnExpr != null) {
                Symbol.Type actualReturnType = (Symbol.Type) visit(returnExpr);
                if (actualReturnType != null && actualReturnType != returnType) {
                    errorLogger.addError(new EMJError("Function '" + funcName + "' should return " + returnType + " but returns " + actualReturnType, returnExpr.getText(), returnExpr.getStart().getLine()));
                }
            }
        }

        symbolTable.exitScope();
        return null;
    }

