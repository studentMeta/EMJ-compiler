    /**
     * Convertit un contexte typeDeclaration en un Symbol.Type.
     *
     * @param ctx le contexte typeDeclaration
     * @return le Symbol.Type correspondant
     */
    private Symbol.Type resolveType(EMJParser.TypeDeclarationContext ctx) {
        if (ctx.TYPE_INT() != null) return Symbol.Type.INT;
        if (ctx.TYPE_CHAR() != null) return Symbol.Type.CHAR;
        if (ctx.TYPE_STRING() != null) return Symbol.Type.STRING;
        if (ctx.TYPE_BOOL() != null) return Symbol.Type.BOOL;
        if (ctx.TYPE_TUPLE() != null) {
            // Type tuple : 👥(innerType)
            Symbol.Type innerType = resolveType(ctx.typeDeclaration());
            switch (innerType) {
                case INT: return Symbol.Type.TUPLE_INT;
                case CHAR: return Symbol.Type.TUPLE_CHAR;
                case STRING: return Symbol.Type.TUPLE_STRING;
                case BOOL: return Symbol.Type.TUPLE_BOOL;
                default: return null;
            }
        }

        return null;
    }
