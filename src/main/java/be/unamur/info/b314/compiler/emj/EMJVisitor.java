    /**
     * @brief Visite la map, vérifie les contraintes de taille et de contenu
     */
    @Override
    public Object visitMap(EMJParser.MapContext ctx) {
        // Visite l'en-tête de la map pour récupérer les dimensions attendues
        visit(ctx.mapHeader());

        int expectedRows = Integer.parseInt(ctx.mapHeader().INT_VALUE(0).getText());
        int expectedCols = Integer.parseInt(ctx.mapHeader().INT_VALUE(1).getText());

        // Vérifie que la taille de la map est au moins 2x2
        if (expectedRows < 2 || expectedCols < 2) {
            errorLogger.addError(new EMJError("Map size must be at least 2x2, got " + expectedRows + "x" + expectedCols, ctx.getText(), ctx.getStart().getLine()));
        }

        // Compte les éléments de la map
        int policeCount = 0;
        int thiefCount = 0;
        int roadCount = 0;
        int totalElements = 0;

        for (EMJParser.MapElementContext elem : ctx.mapElement()) {
            totalElements++;
            if (elem.MAP_POLICE() != null) policeCount++;
            if (elem.MAP_THIEF() != null) thiefCount++;
            if (elem.MAP_ROAD() != null) roadCount++;
        }

        // Exactement une voiture de police
        if (policeCount != 1) {
            errorLogger.addError(new EMJError("Map must contain exactly one police car, found " + policeCount, ctx.getText(), ctx.getStart().getLine()));
        }

        // Au moins un voleur
        if (thiefCount < 1) {
            errorLogger.addError(new EMJError("Map must contain at least one thief", ctx.getText(), ctx.getStart().getLine()));
        }

        // Au moins une route
        if (roadCount < 1) {
            errorLogger.addError(new EMJError("Map must contain at least one road", ctx.getText(), ctx.getStart().getLine()));
        }

        // Vérifie que le nombre total d'éléments correspond à la taille déclarée
        int expectedTotal = expectedRows * expectedCols;
        if (totalElements != expectedTotal) {
            errorLogger.addError(new EMJError("Map header declares " + expectedRows + "x" + expectedCols + " (" + expectedTotal + " cells) but found " + totalElements + " elements", ctx.getText(), ctx.getStart().getLine()));
        }

        return null;
    }


