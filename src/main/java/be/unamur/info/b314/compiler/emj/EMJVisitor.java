    /**
     * @brief Visite la racine du programme, qui doit contenir une map et un programme
     */
    @Override
    public Object visitRoot(EMJParser.RootContext ctx)
    {
        if (ctx.map() != null) {
            return visit(ctx.map());
        }

        if (ctx.program() != null) {
            return visit(ctx.program());
        }

        return null;
    }

