    public Object visitInstruction(EMJParser.InstructionContext ctx)
    {
        // visiter le contenu enfant de l'instruction
        return visitChildren(ctx);
    }

    @Override
    public Object visitLeftExpression(EMJParser.LeftExpressionContext ctx)
    {
        // On récupère le texte de l'emoji et on regarde s'il existe déjà dans la table des symboles
        String name = ctx.EMOJI_ID().getText();
        Symbol symbol = symbolTable.lookupVariable(name);
        if (symbol == null){
            errorLogger.addError(new EMJError("The variable" + name + "is not declared in the context", ctx.getStart().getText(), ctx.getStart().getLine()));
            return null;
        }

        // leftExpression : EMOJI_ID | EMOJI_ID INDEX_0 | EMOJI_ID INDEX_1
        // Si tuple :
        // "Une variable de type 2-tuple indexée (0 ou 1) doit être affectée au même type que le 2-tuple."
        if (ctx.INDEX_0() != null || ctx.INDEX_1() != null) {

            // Un acces tuple en lecture sur une variable non initialisee est interdit
            if (!visitingAssignTarget && !symbol.isInitialized()) {
                errorLogger.addError(new EMJError("Tuple '" + name + "' is used before initialization", ctx.getStart().getText(), ctx.getStart().getLine()));
            }

            switch (symbol.getType()) {
                case TUPLE_INT: return Symbol.Type.INT;
                case TUPLE_BOOL: return Symbol.Type.BOOL;
                case TUPLE_CHAR: return Symbol.Type.CHAR;
                case TUPLE_STRING: return Symbol.Type.STRING;
                default:
                    errorLogger.addError(new EMJError("The variable " + name + " is not a tuple and cannot be indexed", ctx.getStart().getText(), ctx.getStart().getLine()));
                    return null;
            }
        }
        // Si pas tuple :
        return symbol.getType();
    }

    @Override
    public Object visitRightExpression(EMJParser.RightExpressionContext ctx)
    {
        // A right expression can be many things (lines 170-186 of EMJParser)

        // INT_VALUE | CHAR_VALUE | STRING_VALUE | BOOL_TRUE | BOOL_FALSE
        if (ctx.INT_VALUE() != null) {
            String valStr = ctx.INT_VALUE().getText();
            // Vérification du format "0" [cite: 633]
            if (valStr.length() > 1 && valStr.startsWith("0")) {
                errorLogger.addError(new EMJError("Integer cannot start with 0", valStr, ctx.getStart().getLine()));
            }

            long val = Long.parseLong(valStr);
            if (val > 2147483647 || val < -2147483647 ) {
                errorLogger.addError(new EMJError("Integer overflow", valStr, ctx.getStart().getLine()));
            }
        return Symbol.Type.INT;
        }

        if (ctx.CHAR_VALUE() != null) return Symbol.Type.CHAR;
        if (ctx.STRING_VALUE() != null) return Symbol.Type.STRING;
        if (ctx.BOOL_TRUE() != null) return Symbol.Type.BOOL;
        if (ctx.BOOL_FALSE() != null) return Symbol.Type.BOOL;

        //  | leftExpression | functionCall
        if (ctx.leftExpression() != null) return visit(ctx.leftExpression());
        if (ctx.functionCall() != null) return visit(ctx.functionCall());

        //  | LPAREN rightExpression COMMA rightExpression RPAREN -> càd un tuple
        if (ctx.COMMA() != null && ctx.rightExpression().size() == 2) {
            // Sous-type de tuple
            Symbol.Type expressionTypeLeft = (Symbol.Type) visit(ctx.rightExpression(0));
            Symbol.Type expressionTypeRight = (Symbol.Type) visit(ctx.rightExpression(1));
            if (expressionTypeLeft == null || expressionTypeRight == null){
                errorLogger.addError(new EMJError("One element of the tuple is not defined", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            if (expressionTypeLeft != expressionTypeRight) {
                errorLogger.addError(new EMJError("Both elements of the tuple must have the same type", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            switch (expressionTypeLeft) {
                case INT: return Symbol.Type.TUPLE_INT;
                case CHAR: return Symbol.Type.TUPLE_CHAR;
                case STRING: return Symbol.Type.TUPLE_STRING;
                case BOOL: return Symbol.Type.TUPLE_BOOL;
                default: return null;
            }
        }

        //  LPAREN rightExpression RPAREN
        if (ctx.LPAREN() != null && ctx.RPAREN() != null && ctx.rightExpression().size() == 1) {
            return visit(ctx.rightExpression(0));
        }

        //  | NOT rightExpression (réservée aux expressions booléenes)
        if (ctx.NOT() != null && ctx.rightExpression().size() == 1){
            Symbol.Type expressionType = (Symbol.Type) visit(ctx.rightExpression(0));
            if (expressionType == null){
                errorLogger.addError(new EMJError("The negated expression is not defined", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            if (expressionType != Symbol.Type.BOOL) {
                errorLogger.addError(new EMJError("A negated expression must be BOOL type.", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            return Symbol.Type.BOOL;
        }

        //  | rightExpression AND rightExpression (opérateur réservé aux expressions booléenes)
        //  | rightExpression OR rightExpression (opérateur réservé aux expressions booléenes)
        if ((ctx.AND() != null || ctx.OR() != null) && ctx.rightExpression().size() == 2){
            Symbol.Type expressionTypeLeft = (Symbol.Type) visit(ctx.rightExpression(0));
            Symbol.Type expressionTypeRight = (Symbol.Type) visit(ctx.rightExpression(1));

            if (expressionTypeLeft == null  || expressionTypeRight == null){
                errorLogger.addError(new EMJError("One or both expressions linked by AND/OR is/are not defined", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }

            if (expressionTypeLeft != Symbol.Type.BOOL || expressionTypeRight != Symbol.Type.BOOL) {
                errorLogger.addError(new EMJError("Expressions linked by AND/OR must be BOOL type.", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            return Symbol.Type.BOOL;
        }

        //  | rightExpression (LT | GT | LTE | GTE) rightExpression (opérateurs réservés aux expressions booléenes)
        //  | rightExpression (EQ | NEQ) rightExpression (opérateurs réservés aux expressions booléenes)
        if (
                (ctx.LT() != null || ctx.GT() != null || ctx.LTE() != null || ctx.GTE() != null
                || ctx.EQ() != null || ctx.NEQ() != null)
                && ctx.rightExpression().size() == 2)
        {
            Symbol.Type expressionTypeLeft = (Symbol.Type) visit(ctx.rightExpression(0));
            Symbol.Type expressionTypeRight = (Symbol.Type) visit(ctx.rightExpression(1));

            if (expressionTypeLeft == null  || expressionTypeRight == null){
                errorLogger.addError(new EMJError("One or both expressions linked by comparaison operators is/are not defined", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }

            if (expressionTypeLeft != expressionTypeRight) {
                errorLogger.addError(new EMJError("Expressions linked by comparaisons operators must be of same type.", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            return Symbol.Type.BOOL;
        }


        //  | MINUS rightExpression
        if (ctx.MINUS()!=null && ctx.rightExpression().size() == 1){
            Symbol.Type expressionType = (Symbol.Type) visit(ctx.rightExpression(0));
            if (expressionType != Symbol.Type.INT){
                errorLogger.addError(new EMJError("Expression preceded by MINUS sign must be INT type.", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            return Symbol.Type.INT;
        }

        //  | rightExpression (MULT | DIV) rightExpression
        //  | rightExpression (PLUS | MINUS) rightExpression
        if ((ctx.MULT() != null || ctx.DIV() != null || ctx.PLUS() != null || ctx.MINUS() != null) && ctx.rightExpression().size() == 2){
            Symbol.Type expressionTypeLeft = (Symbol.Type) visit(ctx.rightExpression(0));
            Symbol.Type expressionTypeRight = (Symbol.Type) visit(ctx.rightExpression(1));

            if (expressionTypeLeft == null  || expressionTypeRight == null){
                errorLogger.addError(new EMJError("One or both expressions linked by arithmetic operators is/are not defined", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }

            if (expressionTypeLeft != Symbol.Type.INT || expressionTypeRight != Symbol.Type.INT) {
                errorLogger.addError(new EMJError("Expressions linked by arithmetic operators must be INT type.", ctx.getStart().getText(), ctx.getStart().getLine()));
                return null;
            }
            // vérification : "• Aucune division par 0 ne doit survenir."
            if (ctx.DIV() != null) {
                if (ctx.rightExpression(1).INT_VALUE() != null) {
                    if (ctx.rightExpression(1).INT_VALUE().getText().equals("0")) {
                        errorLogger.addError(new EMJError("Division by zero is not allowed", ctx.getStart().getText(), ctx.getStart().getLine()));
                        return null;
                    }
                }
            }

            return Symbol.Type.INT;
        }

        // Gestion des Appels de Fonction dans les expressions
        if (ctx.functionCall() != null) {
            Symbol.Type resType = (Symbol.Type) visit(ctx.functionCall());
            if (resType == Symbol.Type.VOID) {
                errorLogger.addError(new EMJError("Void function cannot be used in an expression", ctx.getText(), ctx.getStart().getLine()));
                return null;
            }
            return resType;
        }

        return null;
    }

    @Override
    public Object visitArithmeticExpression(EMJParser.ArithmeticExpressionContext ctx) {

        // Check whether a variable or component of a tuple is of type INT
        if (ctx.leftExpression() != null) {
            Symbol.Type type = (Symbol.Type) visit(ctx.leftExpression());

            if (type != Symbol.Type.INT) {
                errorLogger.addError(new EMJError("Variable of type " + type + " used in arithmetic expression. Only integer variables can be used in arithmetic expressions.", ctx.leftExpression().getText(), ctx.leftExpression().getStart().getLine()));
            }
        }

        // Check whether a function call has the return type INT
        if (ctx.functionCall() != null) {
            Symbol.Type type = (Symbol.Type) visit(ctx.functionCall());

            if (type != Symbol.Type.INT) {
                errorLogger.addError(new EMJError("Function with return type " + type + " used in arithmetic expression. Only functions with integer return type can be used in arithmetic expressions.", ctx.functionCall().getText(), ctx.functionCall().getStart().getLine()));
            }
        }

        // Avoid division by zero
        if (ctx.DIV() != null && ctx.arithmeticExpression(1).INT_VALUE() != null) {
            int divisor = Integer.parseInt(ctx.arithmeticExpression(1).INT_VALUE().getText());

            if (divisor == 0) {
                errorLogger.addError(new EMJError("Division by zero not allowed.", ctx.arithmeticExpression(1).getText(), ctx.arithmeticExpression(1).getStart().getLine()));
            }
        }

        // Regular cases: visit subexpressions
        /**
        if (ctx.LPAREN() != null && ctx.RPAREN() != null) {
            visit(ctx.arithmeticExpression(0));
        }

        if (ctx.MINUS() != null && ctx.arithmeticExpression().size() == 1) {
            visit(ctx.arithmeticExpression(0));
        }

        if ((ctx.PLUS() != null || ctx.MINUS() != null || ctx.MULT() != null || ctx.DIV() != null) && ctx.arithmeticExpression().size() == 2) {
            visit(ctx.arithmeticExpression(0));
            visit(ctx.arithmeticExpression(1));
        }
        */

        return visitChildren(ctx);
    }

    // =========================================================================
    // LOOPS AND CONDITIONS
    // =========================================================================
    @Override
    public Object visitConditionInstruction(EMJParser.ConditionInstructionContext ctx)
    {
        // Verifier que l'expression de condition est booleenne
        Symbol.Type condType = (Symbol.Type) visit(ctx.rightExpression());
        if (condType != null && condType != Symbol.Type.BOOL) {
            errorLogger.addError(new EMJError("Condition must be a boolean expression, got " + condType, ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
        }

        // push dans le scope
        String scope_name = symbolTable.getCurrentScope() + "_IF_SCOPE";
        symbolTable.enterScope(scope_name);

        // visite interne a la condition
        for (EMJParser.InstructionContext instrCtx : ctx.instruction()) {
            visit(instrCtx);
        }

        // pop le scope
        symbolTable.exitScope();

        // visite du else
        visit(ctx.elseInstruction());

        return null;
    }

    @Override
    public Object visitElseInstruction(EMJParser.ElseInstructionContext ctx)
    {
        // si on skip rien a faire
        if (ctx.SKIP_INSTR() != null) {
            return null;
        }

        // ================== si des instructions sont dispo ==================
        // push dans le scope
        String scope_name = symbolTable.getCurrentScope() + "_ELSE_SCOPE";
        symbolTable.enterScope(scope_name);

        // visite interne a la condition
        for (EMJParser.InstructionContext instrCtx : ctx.instruction()) {
            visit(instrCtx);
        }

        // pop le scope
        symbolTable.exitScope();

        return null;
    }

    @Override
    public Object visitLoopInstruction(EMJParser.LoopInstructionContext ctx)
    {
        // Boucle while : la condition doit etre booleenne
        if (ctx.WHILE() != null) {
            Symbol.Type condType = (Symbol.Type) visit(ctx.rightExpression());
            if (condType != null && condType != Symbol.Type.BOOL) {
                errorLogger.addError(new EMJError("While condition must be a boolean expression, got " + condType, ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
            }
        }

        // Boucle for : l'expression doit etre un entier > 0
        if (ctx.FOR() != null) {
            Symbol.Type exprType = (Symbol.Type) visit(ctx.rightExpression());
            if (exprType != null && exprType != Symbol.Type.INT) {
                errorLogger.addError(new EMJError("For loop expression must be an integer, got " + exprType, ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
            }
            // Verification statique : si l'expression est un litteral, verifier > 0
            if (ctx.rightExpression().INT_VALUE() != null) {
                try {
                    int val = Integer.parseInt(ctx.rightExpression().INT_VALUE().getText());
                    if (val <= 0) {
                        errorLogger.addError(new EMJError("For loop count must be > 0, got " + val, ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
                    }
                } catch (NumberFormatException ignored) {
                }
            }
        }

        // push le scope
        String scope_name = symbolTable.getCurrentScope() + "LOOP";
        symbolTable.enterScope(scope_name);

        // Visiter les instructions du corps de la boucle
        for (EMJParser.InstructionContext instrCtx : ctx.instruction()) {
            visit(instrCtx);
        }

        // pop le scope
        symbolTable.exitScope();

        // test correction charles
        return null;
    }

    // =========================================================================
    // PRÉDÉFINE
    // =========================================================================
    @Override
    public Object visitPredefinedAction(EMJParser.PredefinedActionContext ctx)
    {
        // Actions sans parametres : ✋(), 📻(), 🚨()
        if (ctx.ACT_ARREST() != null || ctx.ACT_SOUND() != null || ctx.ACT_LIGHTS() != null) {
            return null;
        }

        // Actions avec parametre expression arithmetique : ⬆️(X), ⬇️(X), ➡️(X), ⬅️(X)
        if (ctx.ACT_UP() != null || ctx.ACT_DOWN() != null ||
                ctx.ACT_RIGHT() != null || ctx.ACT_LEFT() != null) {
            if (ctx.arithmeticExpression() != null) {
                visit(ctx.arithmeticExpression());
            }

            return null;
        }

        // Mode crazy : 🃏(X) — parametre doit etre entre 1 et 5
        if (ctx.ACT_CRAZY() != null) {
            if (ctx.arithmeticExpression() != null) {
                visit(ctx.arithmeticExpression());

                // Verification statique : si l'expression est un entier litteral
                if (ctx.arithmeticExpression().INT_VALUE() != null) {
                    try {
                        int val = Integer.parseInt(ctx.arithmeticExpression().INT_VALUE().getText());
                        if (val < 1 || val > 5) {
                            errorLogger.addError(new EMJError("Crazy mode parameter must be between 1 and 5, got " + val, ctx.arithmeticExpression().getText(), ctx.arithmeticExpression().getStart().getLine()));
                        }
                    } catch (NumberFormatException ignored) {
                    }
                }
            }

            return null;
        }

        return null;
    }

