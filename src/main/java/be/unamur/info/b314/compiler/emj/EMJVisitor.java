    // =========================================================================
    // VARIABLES
    // =========================================================================
    @Override
    public Object visitVariableDeclaration(EMJParser.VariableDeclarationContext ctx)
    {
        String varName = ctx.EMOJI_ID().getText();
        Symbol.Type varType = resolveType(ctx.typeDeclaration());

        // Verif : la variable ne doit pas etre deja declaree dans cette portee
        if (symbolTable.lookupVariableLocal(varName) != null) {
            errorLogger.addError(new EMJError("Variable '" + varName + "' is already declared in this scope", ctx.getText(), ctx.getStart().getLine()));
            return null;
        }

        // Verif : la variable ne doit pas avoir le meme nom qu'un parametre
        if (symbolTable.lookupParameterLocal(varName) != null) {
            errorLogger.addError(new EMJError("Variable '" + varName + "' has the same name as a parameter", ctx.getText(), ctx.getStart().getLine()));
            return null;
        }

        // Enregistrer la variable dans la table des symboles
        Symbol varSymbol = new Symbol(varName, Symbol.Kind.VARIABLE, varType, symbolTable.getCurrentScope());
        symbolTable.addSymbol(varSymbol);

        // Si initialisee, verifier que le type de l'expression correspond
        if (ctx.rightExpression() != null) {
            Symbol.Type exprType = (Symbol.Type) visit(ctx.rightExpression());
            if (exprType != null && varType != null && exprType != varType) {
                errorLogger.addError(new EMJError("Variable '" + varName + "' declared as " + varType + " but initialized with " + exprType, ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
            }
            varSymbol.setInitialized(true);
        }

        return null;
    }

    @Override
    public Object visitAssignInstruction(EMJParser.AssignInstructionContext ctx)
    {
        // Visiter l'expression gauche pour obtenir son type et verifier la declaration
        visitingAssignTarget = true;
        Symbol.Type leftType = (Symbol.Type) visit(ctx.leftExpression());
        visitingAssignTarget = false;

        // Visiter l'expression droite pour obtenir son type
        Symbol.Type rightType = (Symbol.Type) visit(ctx.rightExpression());

        // Vérifier la compatibilité des types
        if (leftType != null && rightType != null) {
            // Vérification : le retour d'une fonction void ne peut pas etre assigne
            if (rightType == Symbol.Type.VOID) {
                errorLogger.addError(new EMJError("Cannot assign void expression to a variable", ctx.rightExpression().getText(), ctx.rightExpression().getStart().getLine()));
            } else if (leftType != rightType) {
                errorLogger.addError(new EMJError("Type mismatch in assignment: left is " + leftType + " but right is " + rightType, ctx.getStart().getText(), ctx.getStart().getLine()));
            }
        }

        // Marquer la cible comme initialisee apres une affectation
        String targetName = ctx.leftExpression().EMOJI_ID().getText();
        Symbol targetSymbol = symbolTable.lookupVariable(targetName);
        if (targetSymbol != null) {
            targetSymbol.setInitialized(true);
        }

        return null;
    }

