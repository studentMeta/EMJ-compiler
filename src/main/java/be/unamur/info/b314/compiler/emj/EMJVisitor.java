    @Override
    public Object visitProgram(EMJParser.ProgramContext ctx) {
        // Visite de la declaration d'import
        visit(ctx.importDeclaration());

        // --- Passe preliminaire : enregistrer toutes les signatures de fonctions ---
        preliminaryPass = true;

        // Enregistrement de la fonction main dans la table des symboles
        symbolTable.addFunction(new Symbol(
                "main", Symbol.Type.VOID, "global", new Symbol.Type[0], new String[0]));
        declaredFunctions.add("main");

        // Enregistrement des fonctions definies par l'utilisateur
        for (EMJParser.FunctionDeclarationContext funcCtx : ctx.functionDeclaration()) {
            registerFunctionSignature(funcCtx);
        }
        preliminaryPass = false;

        // --- Passe principale : visite du main et des fonctions utilisateur ---
        visit(ctx.mainFunction());

        for (EMJParser.FunctionDeclarationContext funcCtx : ctx.functionDeclaration()) {
            visit(funcCtx);
        }

        return null;
    }

    /**
     * Enregistre la signature d'une fonction pendant la passe preliminaire.
     * Permet d'appeler des fonctions avant la visite de leur corps complet.
     *
     * @param ctx le contexte functionDeclaration
     */
    private void registerFunctionSignature(EMJParser.FunctionDeclarationContext ctx) {
        String funcName;
        Symbol.Type returnType;

        if (ctx.typeDeclaration() == null) {
            // fonction void
            funcName = ctx.EMOJI_ID().getText();
            returnType = Symbol.Type.VOID;
        } else {
            // fonction typee
            funcName = ctx.EMOJI_ID().getText();
            returnType = resolveType(ctx.typeDeclaration());
        }

        // Verifier les doublons de noms de fonction
        if (symbolTable.functionExists(funcName)) {
            errorLogger.addError(new EMJError("Function '" + funcName + "' is already declared", ctx.getText(), ctx.getStart().getLine()));
            return;
        }

        // Extraction des types et noms des parametres
        EMJParser.FunctionParametersContext paramsCtx = ctx.functionParameters();
        List<Symbol.Type> paramTypes = new ArrayList<>();
        List<String> paramNames = new ArrayList<>();

        if (paramsCtx != null && paramsCtx.typeDeclaration() != null) {
            for (int i = 0; i < paramsCtx.typeDeclaration().size(); i++) {
                paramTypes.add(resolveType(paramsCtx.typeDeclaration(i)));
                paramNames.add(paramsCtx.EMOJI_ID(i).getText());
            }
        }

        Symbol funcSymbol = new Symbol(
                funcName,
                returnType,
                "global",
                paramTypes.toArray(new Symbol.Type[0]),
                paramNames.toArray(new String[0])
        );
        symbolTable.addFunction(funcSymbol);
        declaredFunctions.add(funcName);
    }

